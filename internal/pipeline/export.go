// BuildRawPrompt builds a combined prompt string from scaffold fields.
func BuildRawPrompt(scaffold *PromptScaffold) string {
	var parts []string
	for _, field := range DimensionFields {
		if val, ok := scaffold.Fields[field]; ok && val != "" {
			parts = append(parts, val)
		}
	}

	prompt := strings.Join(parts, ", ")
	if len(scaffold.Negative) > 0 {
		negStr := strings.Join(scaffold.Negative, ", ")
		prompt += " --negative " + negStr
	}
	return prompt
}

